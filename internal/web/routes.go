package web

// routes registers the signed-in pages, fragments, and actions.
func (s *Server) routes() {
	m := s.mux
	m.HandleFunc("GET /{$}", s.authed(s.dashboard))
	m.HandleFunc("GET /fragments/servers", s.authed(s.serversFragment))
	m.HandleFunc("GET /fragments/attention", s.authed(s.attentionFragment))
	m.HandleFunc("GET /events", s.authed(s.events))
	m.HandleFunc("GET /account", s.authed(s.account))
	m.HandleFunc("GET /fragments/account/sessions", s.authed(s.accountSessions))
	m.HandleFunc("POST /account/password", s.authed(s.changePassword))
	m.HandleFunc("POST /account/sessions/{id}/revoke", s.authed(s.revokeSession))
	m.HandleFunc("GET /servers/{id}", s.authed(s.serverDetail))
	m.HandleFunc("GET /fragments/servers/{id}/live", s.authed(s.detailLive))
	m.HandleFunc("GET /fragments/servers/{id}/overview", s.authed(s.detailOverview))
	m.HandleFunc("GET /fragments/servers/{id}/activity", s.authed(s.detailActivity))
	m.HandleFunc("GET /fragments/servers/{id}/operations/{operation}", s.authed(s.detailOperation))
	m.HandleFunc("POST /servers/{id}/availability", s.admin(s.configureAvailability))
	m.HandleFunc("POST /servers/{id}/binding-review", s.admin(s.reviewBinding))
	m.HandleFunc("GET /fragments/servers/{id}/backups", s.admin(s.backupList))
	m.HandleFunc("GET /fragments/servers/{id}/backups/preflight", s.authed(s.backupPreflight))
	m.HandleFunc("POST /servers/{id}/backups", s.authed(s.createBackup))
	m.HandleFunc("GET /servers/{id}/backups/{backup}/download", s.admin(s.downloadBackup))
	m.HandleFunc("POST /servers/{id}/backups/{backup}/delete", s.admin(s.deleteBackup))
	m.HandleFunc("POST /servers/{id}/restores", s.admin(s.restoreBackup))
	m.HandleFunc("GET /fragments/servers/{id}/update", s.authed(s.updatePanel))
	m.HandleFunc("POST /servers/{id}/updates", s.admin(s.queueUpdate))
	m.HandleFunc("GET /fragments/servers/{id}/schedules", s.authed(s.scheduleList))
	m.HandleFunc("POST /fragments/servers/{id}/schedules/preview", s.authed(s.previewSchedule))
	m.HandleFunc("POST /servers/{id}/schedules", s.authed(s.saveSchedule))
	m.HandleFunc("POST /servers/{id}/schedules/{schedule}", s.authed(s.saveSchedule))
	m.HandleFunc("POST /servers/{id}/schedules/{schedule}/toggle", s.authed(s.toggleSchedule))
	m.HandleFunc("POST /servers/{id}/schedules/{schedule}/delete", s.authed(s.deleteSchedule))
	m.HandleFunc("GET /console/{id}", s.authed(s.consolePage))
	m.HandleFunc("GET /ws/console/{id}", s.authed(s.consoleSocket))
	m.HandleFunc("GET /files/{id}", s.authed(s.filesPage))
	m.HandleFunc("GET /fragments/files/{id}", s.authed(s.filesList))
	m.HandleFunc("GET /fragments/files/{id}/dialog", s.authed(s.fileDialog))
	m.HandleFunc("GET /fragments/files/{id}/preview", s.authed(s.filePreview))
	m.HandleFunc("GET /files/{id}/download", s.authed(s.fileDownload))
	m.HandleFunc("PUT /files/{id}/upload", s.authed(s.fileUpload))
	m.HandleFunc("POST /files/{id}/create", s.authed(s.fileChange("create")))
	m.HandleFunc("POST /files/{id}/rename", s.authed(s.fileChange("rename")))
	m.HandleFunc("POST /files/{id}/delete", s.authed(s.fileChange("delete")))
	m.HandleFunc("POST /servers/{id}/start", s.authed(s.startServer))
	m.HandleFunc("POST /servers/{id}/stop", s.authed(s.queueLifecycle("stop")))
	m.HandleFunc("POST /servers/{id}/restart", s.authed(s.queueLifecycle("restart")))
}
